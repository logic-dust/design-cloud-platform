package command

import (
	"bytes"
	"context"
	json "design-cloud-engine/internal/platform/jsoncodec"
	"fmt"
	"io"
	"net/http"
	"net/url"
	"os"
	"path/filepath"
	"strings"
	"time"

	"design-cloud-engine/cmd/engine/console"
	"design-cloud-engine/internal/platform/config"
	fsutil "design-cloud-engine/internal/platform/fs"
)

const (
	registerTimeout       = 5 * time.Second
	registerErrorBodySize = 64 << 10
)

var registerHTTPClient = &http.Client{Timeout: registerTimeout}

func runRegisterCommand(args []string) error {
	fs := newCommandFlagSet("register", os.Stderr)
	var hostname, portalURL, token, dataDir string
	var insecureHTTP bool

	fs.StringVar(&hostname, "hostname", "", "Node ID to bootstrap (defaults to os.Hostname(); use only to sign for another machine)")
	fs.StringVar(&portalURL, "portal-url", "", "Portal HTTP(S) URL, e.g. https://mgt01:8443 (required)")
	fs.StringVar(&token, "token", "", "Bootstrap token generated by the server (required)")
	fs.StringVar(&dataDir, "data-dir", "", "Certificate base directory (platform default when omitted)")
	fs.BoolVar(&insecureHTTP, "insecure-http", false, "Allow unencrypted plain HTTP portal URL (INSECURE: transmits OTP token and private key in plaintext)")
	fs.Usage = func() {
		console.PrintStderr("Usage: node register --portal-url <url> --token <token> [--insecure-http] [--data-dir <dir>] [--hostname <nodeID>]\n\n")
		console.PrintStderr("Bootstrap node certificate materials via OTP token and write cert/key/ca under the\n")
		console.PrintStderr("conventional cluster cert layout. Does not read config.toml.\n\n")
		fs.PrintDefaults()
	}

	if err := fs.Parse(args); err != nil {
		return fmt.Errorf("register parse error: %w", err)
	}

	if token == "" {
		return fmt.Errorf("--token is required")
	}
	if portalURL == "" {
		return fmt.Errorf("--portal-url <url> is required")
	}
	if err := validatePortalURL(portalURL, insecureHTTP); err != nil {
		return err
	}

	// NodeID strictly equals os.Hostname() unless explicitly signing for another node.
	nodeID := hostname
	if nodeID == "" {
		hn, err := os.Hostname()
		if err != nil || strings.TrimSpace(hn) == "" {
			return fmt.Errorf("resolve local hostname: %w", err)
		}
		nodeID = hn
	}

	certPaths, err := config.ResolveClusterCertPaths(config.CertInput{
		DataDir: dataDir, NodeID: nodeID,
	})
	if err != nil {
		return err
	}

	apiURL := fmt.Sprintf("%s/api/nodes/%s/registration", strings.TrimRight(portalURL, "/"), nodeID)
	console.PrintStdout("Registering node '%s' via %s...\n", nodeID, apiURL)

	// Pre-check target directories before sending the request, to avoid burning
	// the one-time OTP token on a failed write. Must follow the permission
	// matrix: certs/cluster is SHARED (0755), node dir is PRIVATE (0700).
	if err := fsutil.MkdirShared(filepath.Dir(certPaths.CA)); err != nil {
		return fmt.Errorf("cluster cert dir not writable: %w", err)
	}
	if err := fsutil.MkdirPrivate(certPaths.CertDir); err != nil {
		return fmt.Errorf("node cert dir not writable: %w", err)
	}
	if keyDir := filepath.Dir(certPaths.Key); keyDir != certPaths.CertDir {
		if err := fsutil.MkdirPrivate(keyDir); err != nil {
			return fmt.Errorf("node key dir not writable: %w", err)
		}
	}

	payload := map[string]string{"token": token}
	jsonData, err := json.Marshal(payload)
	if err != nil {
		return fmt.Errorf("marshal registration payload: %w", err)
	}

	ctx, cancel := context.WithTimeout(context.Background(), registerTimeout)
	defer cancel()

	req, err := http.NewRequestWithContext(ctx, http.MethodPost, apiURL, bytes.NewBuffer(jsonData))
	if err != nil {
		return fmt.Errorf("build registration request: %w", err)
	}
	req.Header.Set("Content-Type", "application/json")

	resp, err := registerHTTPClient.Do(req)
	if err != nil {
		return fmt.Errorf("http request failed: %w", err)
	}
	defer func(body io.ReadCloser) { _ = body.Close() }(resp.Body)

	if resp.StatusCode != http.StatusOK {
		body, _ := io.ReadAll(io.LimitReader(resp.Body, registerErrorBodySize))
		var errResp struct {
			Message string `json:"message"`
		}
		if err := json.Unmarshal(body, &errResp); err == nil && errResp.Message != "" {
			return fmt.Errorf("bootstrap failed (%d): %s", resp.StatusCode, errResp.Message)
		}
		if len(body) > 0 {
			return fmt.Errorf("bootstrap failed (%d): %s", resp.StatusCode, string(body))
		}
		return fmt.Errorf("bootstrap failed (%d)", resp.StatusCode)
	}

	// Portal bootstrap 响应只需要证书材料；用本地 DTO 而不是服务层类型，
	// 因为 CLI 在这里是纯 HTTP 客户端，不应为三个字段 import 整个 node 服务包。
	var result struct {
		Data struct {
			ServerAddr    string    `json:"serverAddr"`
			CertPEM       string    `json:"certPem"`
			KeyPEM        string    `json:"keyPem"`
			CAPEM         string    `json:"caPem"`
			CertExpiresAt time.Time `json:"certExpiresAt"`
		} `json:"data"`
	}
	if err := json.UnmarshalRead(resp.Body, &result); err != nil {
		return fmt.Errorf("decode bootstrap response: %w", err)
	}
	if result.Data.CertPEM == "" || result.Data.KeyPEM == "" || result.Data.CAPEM == "" {
		return fmt.Errorf("bootstrap response missing cert/key/ca materials")
	}

	if err := fsutil.WriteSharedFile(certPaths.Cert, []byte(result.Data.CertPEM)); err != nil {
		return fmt.Errorf("write cert file: %w", err)
	}
	if err := fsutil.WritePrivateFile(certPaths.Key, []byte(result.Data.KeyPEM)); err != nil {
		return fmt.Errorf("write key file: %w", err)
	}
	if err := fsutil.WriteSharedFile(certPaths.CA, []byte(result.Data.CAPEM)); err != nil {
		return fmt.Errorf("write CA file: %w", err)
	}

	console.PrintlnStdout("Successfully bootstrapped node materials:")
	console.PrintStdout("   Server Addr : %s\n", result.Data.ServerAddr)
	console.PrintStdout("   Cert        : %s\n", certPaths.Cert)
	console.PrintStdout("   Key         : %s\n", certPaths.Key)
	console.PrintStdout("   CA          : %s\n", certPaths.CA)
	console.PrintStdout("   Expires     : %s\n", result.Data.CertExpiresAt.UTC().Format(time.RFC3339))
	return nil
}

// validatePortalURL enforces a full http(s) URL with a host.
// Plain 'http://' is rejected by default to protect against MitM eavesdropping
// and credential/certificate tampering, unless insecureHTTP is explicitly enabled.
func validatePortalURL(raw string, insecureHTTP bool) error {
	u, err := url.Parse(raw)
	if err != nil {
		return fmt.Errorf("invalid --portal-url %q: %w", raw, err)
	}
	if u.Scheme != "http" && u.Scheme != "https" {
		return fmt.Errorf("--portal-url must be a full http(s) URL (e.g. https://mgt01:8443); got %q", raw)
	}
	if u.Host == "" {
		return fmt.Errorf("--portal-url %q is missing a host", raw)
	}
	if u.Scheme == "http" {
		if !insecureHTTP {
			console.PrintStderr("SECURITY ERROR: --portal-url uses unencrypted 'http://' scheme (%s)!\n", raw)
			console.PrintStderr("Transmitting OTP tokens and receiving node private keys/CA certificates\n")
			console.PrintStderr("over plain HTTP is vulnerable to Man-in-the-Middle (MitM) eavesdropping and tampering.\n\n")
			console.PrintStderr("Recommended: Use 'https://' with a valid SSL/TLS certificate.\n")
			console.PrintStderr("To bypass this check and proceed at your own risk, pass '--insecure-http'.\n\n")
			return fmt.Errorf("insecure http portal URL rejected: %q (use https:// or pass --insecure-http to override)", raw)
		}
		console.PrintStderr("SECURITY WARNING: Proceeding with unencrypted HTTP registration via %s (--insecure-http enabled). Credentials are NOT protected in transit!\n", raw)
	}
	return nil
}
